package com.example.ungdungchiasecaycanh.ui.auth;

import android.app.Activity;
import android.content.Context;
import android.os.CancellationSignal;

import androidx.annotation.Nullable;
import androidx.core.content.ContextCompat;
import androidx.credentials.ClearCredentialStateRequest;
import androidx.credentials.Credential;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.CustomCredential;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.ClearCredentialException;
import androidx.credentials.exceptions.GetCredentialCancellationException;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.credentials.exceptions.NoCredentialException;

import com.example.ungdungchiasecaycanh.R;
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;

/**
 * "Continue with Google" through Credential Manager: shows the Google account picker and returns
 * a Google ID token, which the ViewModel exchanges for a Firebase session. The OAuth web client
 * ID comes from google-services.json (default_web_client_id) once Google sign-in is enabled.
 */
public final class GoogleSignInHelper {

    public interface Callback {
        void onIdToken(String idToken);
        /** {@code message} is 0 when the member simply closed the picker. */
        void onFailure(int message);
    }

    private GoogleSignInHelper() { }

    /** Web client ID generated by the google-services plugin, or null when not configured yet. */
    @Nullable
    static String webClientId(Context context) {
        int id = context.getResources().getIdentifier("default_web_client_id", "string", context.getPackageName());
        return id == 0 ? null : context.getString(id);
    }

    public static void signIn(Activity activity, Callback callback) {
        String clientId = webClientId(activity);
        if (clientId == null || clientId.isEmpty()) {
            callback.onFailure(R.string.auth_google_not_configured);
            return;
        }
        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(new GetSignInWithGoogleOption.Builder(clientId).build())
                .build();
        CredentialManager.create(activity).getCredentialAsync(activity, request, new CancellationSignal(),
                ContextCompat.getMainExecutor(activity),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override public void onResult(GetCredentialResponse response) {
                        Credential credential = response.getCredential();
                        if (credential instanceof CustomCredential
                                && GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL.equals(credential.getType())) {
                            try {
                                callback.onIdToken(GoogleIdTokenCredential.createFrom(credential.getData()).getIdToken());
                            } catch (Exception error) {
                                callback.onFailure(R.string.auth_google_error);
                            }
                        } else {
                            callback.onFailure(R.string.auth_google_error);
                        }
                    }

                    @Override public void onError(GetCredentialException error) {
                        if (error instanceof GetCredentialCancellationException) callback.onFailure(0);
                        else if (error instanceof NoCredentialException) callback.onFailure(R.string.auth_google_no_account);
                        else callback.onFailure(R.string.auth_google_error);
                    }
                });
    }

    /** On sign-out, so the next "Continue with Google" shows the account picker again. */
    public static void clearState(Context context) {
        CredentialManager.create(context).clearCredentialStateAsync(new ClearCredentialStateRequest(),
                new CancellationSignal(), ContextCompat.getMainExecutor(context),
                new CredentialManagerCallback<Void, ClearCredentialException>() {
                    @Override public void onResult(Void result) { }
                    @Override public void onError(ClearCredentialException error) { }
                });
    }
}
